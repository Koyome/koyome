def f(v):
    s = ('%.2f' % v).rstrip('0').rstrip('.')
    return '0' if s in ('', '-0') else s


# ---------------------------------------------------------------- helpers
def circle(r, col, w=1.0, dash=None, fill='none', cx=C, cy=C, op=None):
    d = ' stroke-dasharray="%s"' % dash if dash else ''
    o = ' opacity="%s"' % op if op else ''
    return ('<circle cx="%s" cy="%s" r="%s" fill="%s" stroke="%s" '
            'stroke-width="%s"%s%s/>' % (f(cx), f(cy), f(r), fill, col, f(w), d, o))


def line(x1, y1, x2, y2, col, w=1.0, dash=None, op=None):
    d = ' stroke-dasharray="%s"' % dash if dash else ''
    o = ' opacity="%s"' % op if op else ''
    return ('<line x1="%s" y1="%s" x2="%s" y2="%s" stroke="%s" '
            'stroke-width="%s"%s%s/>' % (f(x1), f(y1), f(x2), f(y2), col, f(w), d, o))


def path(d, col, w=1.0, dash=None, fill='none', op=None, fill_op=None, cls=None,
         style=None):
    dd = ' stroke-dasharray="%s"' % dash if dash else ''
    o = ' opacity="%s"' % op if op else ''
    fo = ' fill-opacity="%s"' % fill_op if fill_op else ''
    c = ' class="%s"' % cls if cls else ''
    s = ' style="%s"' % style if style else ''
    return ('<path%s d="%s" fill="%s"%s stroke="%s" stroke-width="%s"%s%s%s/>'
            % (c, d, fill, fo, col, f(w), dd, o, s))


def ellipse(rx, ry, col, w=1.0, dash=None, cx=C, cy=C, op=None):
    d = ' stroke-dasharray="%s"' % dash if dash else ''
    o = ' opacity="%s"' % op if op else ''
    return ('<ellipse cx="%s" cy="%s" rx="%s" ry="%s" fill="none" stroke="%s" '
            'stroke-width="%s"%s%s/>' % (f(cx), f(cy), f(rx), f(ry), col, f(w), d, o))


def polyline(pts, col, w=1.0, close=False, dash=None, op=None):
    d = 'M ' + ' L '.join('%s %s' % (f(x), f(y)) for x, y in pts)
    if close:
        d += ' Z'
    return path(d, col, w, dash=dash, op=op)


def reg(n, r, cx=C, cy=C, off=0.0):
    return [(cx + r * math.cos(math.radians(off + i * 360.0 / n)),
             cy + r * math.sin(math.radians(off + i * 360.0 / n))) for i in range(n)]


def text(x, y, s, col, size=13, anchor='middle', ls=1.2, op=None):
    o = ' opacity="%s"' % op if op else ''
    return ('<text x="%s" y="%s" text-anchor="%s" font-family="Menlo, Consolas, '
            'monospace" font-size="%s" letter-spacing="%s" fill="%s"%s>%s</text>'
            % (f(x), f(y), anchor, f(size), f(ls), col, o, s))


def arc(cx, cy, r, a0, a1, sweep=1):
    """Hairline arc between two angles (degrees, screen space)."""
    p0 = (cx + r * math.cos(math.radians(a0)), cy + r * math.sin(math.radians(a0)))
    p1 = (cx + r * math.cos(math.radians(a1)), cy + r * math.sin(math.radians(a1)))
    return 'M %s %s A %s %s 0 0 %d %s %s' % (f(p0[0]), f(p0[1]), f(r), f(r),
                                             sweep, f(p1[0]), f(p1[1]))


def lcg(seed):
    s = seed
    while True:
        s = (1103515245 * s + 12345) % (1 << 31)
        yield s / float(1 << 31)


# ---------------------------------------------------------------- materials
def light_grad(p, ident='k-light', deg=LIGHT_DEG):
    """One key light for the entire drawing - every stroke reads the same source."""
    rad = math.radians(deg)
    x1 = C - 520 * math.cos(rad)
    y1 = C - 520 * math.sin(rad)
    x2 = C + 520 * math.cos(rad)
    y2 = C + 520 * math.sin(rad)
    return ('<linearGradient id="%s" gradientUnits="userSpaceOnUse" '
            'x1="%s" y1="%s" x2="%s" y2="%s">'
            '<stop offset="0" stop-color="%s"/>'
            '<stop offset="0.44" stop-color="%s"/>'
            '<stop offset="0.68" stop-color="%s"/>'
            '<stop offset="1" stop-color="%s"/></linearGradient>'
            % (ident, f(x1), f(y1), f(x2), f(y2),
               p['gloss'], p['ink'], p['coal'], p['bounce']))


def metal_grad(p, ident, deg=LIGHT_DEG + 96.0):
    """Brushed metal: many short stops across one shared light direction."""
    rad = math.radians(deg)
    x1 = C - 560 * math.cos(rad)
    y1 = C - 560 * math.sin(rad)
    x2 = C + 560 * math.cos(rad)
    y2 = C + 560 * math.sin(rad)
    stops = ''.join('<stop offset="%s" stop-color="%s"/>'
                    % (f(i / (len(p['metal']) - 1.0)), c)
                    for i, c in enumerate(p['metal']))
    return ('<linearGradient id="%s" gradientUnits="userSpaceOnUse" '
            'x1="%s" y1="%s" x2="%s" y2="%s">%s</linearGradient>'
            % (ident, f(x1), f(y1), f(x2), f(y2), stops))


def lit_line(p, r, w=1.0, dash=None, op=None, cx=C, cy=C):
    """Hairline plus its own directional pass: a wire that knows the light."""
    return (circle(r, p['ink'], w, dash=dash, cx=cx, cy=cy, op=op)
            + circle(r, 'url(#k-light)', max(w + 1.2, 1.7), dash=dash, cx=cx, cy=cy,
                     op=f(0.42 * float(op or 1))))


def band_ring(p, r, w, ident=None, op=None):
    """Thick metal band: gradient body + key edge lit + shadow edge coal."""
    stroke = 'url(#%s)' % ident if ident else p['ink']
    out = '<circle cx="%s" cy="%s" r="%s" fill="none" stroke="%s" stroke-width="%s" opacity="%s"/>' % (
        f(C), f(C), f(r), stroke, f(w), op or p['band'])
    out += path(arc(C, C, r + w / 2.0 - 0.4, LIGHT_DEG - 96, LIGHT_DEG + 96),
                p['gloss'], 0.9, op='0.7')
    out += path(arc(C, C, r - w / 2.0 + 0.4, LIGHT_DEG + 84, LIGHT_DEG + 276),
                p['coal'], 0.85, op='0.55')
    return out


def stipple(p, cx, cy, r0, r1, n, seed=7, size=0.62, op=0.22):
    """Deterministic micro grain - real texture without a single pixel filter."""
    g = lcg(seed)
    alpha = f(float(op))
    out = []
    for _ in range(n):
        a = g.__next__() * 2 * math.pi
        rr = r0 + (r1 - r0) * math.sqrt(g.__next__())
        out.append(circle(size, p['coal'], 0, cx=cx + rr * math.cos(a),
                          cy=cy + rr * math.sin(a), fill=p['coal'], op=alpha))
    return ''.join(out)


