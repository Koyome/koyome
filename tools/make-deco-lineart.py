def orbit_keyframes(name, rx, ry, base_theta, rot_deg=0.0, cx=C, cy=C, steps=48):
    """translate keyframes for a marker riding an ellipse starting at base_theta."""
    rot = math.radians(rot_deg)
    rows = []

    def pt(t):
        px0, py0 = rx * math.cos(t), ry * math.sin(t)
        return (cx + px0 * math.cos(rot) - py0 * math.sin(rot),
                cy + px0 * math.sin(rot) + py0 * math.cos(rot))

    bx, by = pt(math.radians(base_theta))
    for j in range(steps + 1):
        t = math.radians(base_theta) + 2 * math.pi * j / steps
        px, py = pt(t)
        rows.append('      %s%% { transform: translate(%spx, %spx); }'
                    % (f(100.0 * j / steps), f(px - bx), f(py - by)))
    return '@keyframes %s {\n%s\n    }' % (name, '\n'.join(rows))


# --------------------------------------------------- 1. armillary sphere
def armillary(p):
    defs, body, style = [], [], [RM_RULE]
    R = 300.0
    ERX, ERY = 284.0, 88.0
    TILT = -23.44

    # one key light for the whole instrument, plus three anisotropic metals
    defs.append(light_grad(p))
    defs.append(metal_grad(p, 'k-metal'))
    defs.append(metal_grad(p, 'k-metal-b', LIGHT_DEG - 34.0))
    defs.append(metal_grad(p, 'k-metal-c', LIGHT_DEG + 46.0))

    # construction square
    body.append('<rect x="100" y="100" width="600" height="600" fill="none" '
                'stroke="%s" stroke-width="0.8" stroke-dasharray="5 8"/>' % p['faint'])

    # letterpress echo: the bezel pressing into the paper (a cast stroke, never
    # a filled disc - the deco has to stay transparent line art)
    body.append(circle(R, p['shadow'], 7.0, cx=C + 3.2, cy=C + 4.2, op='0.07'))
    body.append(circle(R, p['gloss'], 0.9, cx=C - 1.4, cy=C - 1.8, op='0.5'))

    # outer bezel: real thickness, gradient body, key/shadow edges, metal grain
    body.append(band_ring(p, R, 8.5, 'k-metal'))
    body.append(lit_line(p, R + 4.6, 1.0))
    body.append(lit_line(p, R - 4.6, 1.0))
    body.append(stipple(p, C, C, R - 4.9, R + 4.9, 260, seed=13, size=0.55, op=0.17))
    # rivets around the bezel, each with a highlight facing the key light
    for i in range(24):
        a = math.radians(i * 15)
        rx, ry = C + R * math.cos(a), C + R * math.sin(a)
        face = 0.5 + 0.5 * math.cos(math.radians(i * 15) - math.radians(LIGHT_DEG))
        body.append(circle(2.5, p['coal'], 0, cx=rx, cy=ry, fill=p['coal'],
                           op=f(0.35 + 0.25 * (1 - face))))
        body.append(circle(1.1, p['gloss'], 0,
                           cx=rx - 0.9 * math.cos(math.radians(LIGHT_DEG)),
                           cy=ry - 0.9 * math.sin(math.radians(LIGHT_DEG)),
                           fill=p['gloss'], op=f(0.35 + 0.5 * face)))

    # graduation dial - STATIC, and light-aware: ticks facing the key light read
    # brighter, ticks on the shadow side fall away
    dial = []
    dial.append(lit_line(p, 286, 0.9))
    dial.append(circle(238, p['faint'], 0.9, dash='1 9'))
    for i in range(72):
        deg = i * 5
        a = math.radians(deg)
        face = 0.5 + 0.5 * math.cos(a - math.radians(LIGHT_DEG))
        if i % 18 == 0:
            ln, base, w = 24.0, p['accent'], 1.2
        elif i % 6 == 0:
            ln, base, w = 15.0, p['ink'], 1.0
        elif i % 2 == 0:
            ln, base, w = 9.0, p['soft'], 0.85
        else:
            ln, base, w = 5.0, p['faint'], 0.7
        col = p['gloss'] if (face > 0.78 and i % 6 == 0) else base
        c, s = math.cos(a), math.sin(a)
        dial.append(line(C + 286 * c, C + 286 * s, C + (286 - ln) * c,
                         C + (286 - ln) * s, col, w, op=f(0.42 + 0.5 * face)))
    body.append(''.join(dial))

    # three great-circle rings, each with body + thickness twin + lit edge
    body.append('<ellipse cx="400" cy="400" rx="%s" ry="%s" fill="none" '
                'stroke="url(#k-metal-b)" stroke-width="4.8" opacity="%s"/>'
                % (f(ERX), f(ERY), p['band']))
    body.append(ellipse(ERX, ERY, 'url(#k-light)', 2.4, op='0.55'))
    body.append(ellipse(ERX, ERY, p['ink'], 1.0))
    body.append(ellipse(ERX - 6.5, ERY - 6.5, p['coal'], 0.55, op='0.45'))
    body.append(ellipse(ERY, ERX, p['soft'], 0.9))
    body.append(ellipse(ERY, ERX, 'url(#k-light)', 2.0, op='0.45'))
    body.append(ellipse(ERY + 6.5, ERX + 6.5, p['faint'], 0.5))
    body.append('<g transform="rotate(%s 400 400)">'
                '<ellipse cx="400" cy="400" rx="%s" ry="%s" fill="none" '
                'stroke="url(#k-metal-c)" stroke-width="5.4" opacity="%s"/>'
                '<ellipse cx="400" cy="400" rx="%s" ry="%s" fill="none" '
                'stroke="url(#k-light)" stroke-width="2.4" opacity="0.5"/>'
                '<ellipse cx="400" cy="400" rx="%s" ry="%s" fill="none" stroke="%s" '
                'stroke-width="1.15"/>'
                '<ellipse cx="400" cy="400" rx="%s" ry="%s" fill="none" stroke="%s" '
                'stroke-width="0.55" opacity="0.5"/></g>'
                % (f(TILT), f(ERX), f(ERY), p['band'],
                   f(ERX), f(ERY), f(ERX), f(ERY), p['ink'],
                   f(ERX - 6), f(ERY - 6), p['coal']))

    # polar axis: twin walls for thickness, caps, hairline core
    axis = []
    for off in (-3.2, 3.2):
        axis.append(line(C + off, 104, C + off, 696, p['soft'], 0.75))
    axis.append(line(C, 86, C, 714, p['ink'], 0.85, dash='7 6'))
    for yy in (104.0, 696.0):
        axis.append(circle(9, p['ink'], 1.0, cy=yy))
        axis.append(circle(9, 'url(#k-light)', 1.8, cy=yy, op='0.5'))
        axis.append(circle(3, p['accent'] if yy == 104.0 else p['soft'], 0, cy=yy,
                           fill=p['accent'] if yy == 104.0 else p['soft']))
    axis.append(line(126, C, 674, C, p['soft'], 0.8, dash='6 8'))
    body.extend(axis)

    # the alidade: the only rotating part of the instrument itself, and it creeps
    style.append('''
    .k-alidade { animation-name: koyo-spin; animation-duration: 320s; }
    .k-sweep   { animation-name: koyo-spin; animation-duration: 52s; }
    .k-orb-glint-a { animation-name: k-orb-glint-a; animation-duration: 88s; }
    .k-orb-glint-b { animation-name: k-orb-glint-b; animation-duration: 64s; }
    .k-orb-planet  { animation-name: k-orb-planet; animation-duration: 96s; }
    .k-orb-moon    { animation-name: k-orb-moon; animation-duration: 27s; }
    .k-orb-node    { animation-name: k-orb-node; animation-duration: 132s; }
    @keyframes koyo-spin { from { transform: rotate(0deg); } to { transform: rotate(360deg); } }
''')
    style.append(orbit_keyframes('k-orb-glint-a', ERX, ERY, -12.0, rot_deg=TILT))
    style.append(orbit_keyframes('k-orb-glint-b', ERX, ERY, 150.0))
    style.append(orbit_keyframes('k-orb-planet', ERX, ERY, -34.0, rot_deg=TILT))
    style.append(orbit_keyframes('k-orb-moon', ERX, ERY, 126.0, rot_deg=TILT))
    style.append(orbit_keyframes('k-orb-node', ERX, ERY, 18.0))

    def epoint(rx, ry, th, rot):
        t = math.radians(th)
        rr = math.radians(rot)
        px0, py0 = rx * math.cos(t), ry * math.sin(t)
        return (C + px0 * math.cos(rr) - py0 * math.sin(rr),
                C + px0 * math.sin(rr) + py0 * math.cos(rr))

    # light gliding along the metal: a short gloss arc riding each ring
    gx, gy = epoint(ERX, ERY, -12.0, TILT)
    body.append('<g class="k-anim k-orb-glint-a">'
                '<path d="%s" fill="none" stroke="%s" stroke-width="1.7" '
                'opacity="0.8" transform="rotate(%s %s %s)"/>'
                '</g>' % (arc(gx, gy, 48, 175, 185), p['gloss'],
                          f(TILT), f(gx), f(gy)))
    hx, hy = epoint(ERX, ERY, 150.0, 0.0)
    body.append('<g class="k-anim k-orb-glint-b">'
                + path(arc(hx, hy, 52, -4, 4), p['gloss'], 1.5, op='0.6')
                + '</g>')

    # moving bodies, each with its own period
    px, py = epoint(ERX, ERY, -34.0, TILT)
    mk = []
    mk.append(circle(14, p['accent'], 0.9, cx=px, cy=py))
    mk.append(circle(6.5, p['accent'], 0, cx=px, cy=py, fill=p['accent']))
    mk.append(circle(2.2, p['gloss'], 0,
                     cx=px - 2.2 * math.cos(math.radians(LIGHT_DEG)),
                     cy=py - 2.2 * math.sin(math.radians(LIGHT_DEG)),
                     fill=p['gloss'], op='0.85'))
    mk.append(path(arc(px, py, 6.5, LIGHT_DEG - 40, LIGHT_DEG + 40),
                   p['gloss'], 1.4, op='0.6'))
    body.append('<g class="k-anim k-orb-planet">' + ''.join(mk) + '</g>')

    mx, my = epoint(ERX, ERY, 126.0, TILT)
    body.append('<g class="k-anim k-orb-moon">'
                + circle(3.6, p['ink'], 0, cx=mx, cy=my, fill=p['ink'], op='0.85')
                + circle(1.2, p['gloss'], 0, cx=mx - 1.2, cy=my - 1.2,
                         fill=p['gloss'], op='0.7')
                + '</g>')

    nx, ny = epoint(ERX, ERY, 18.0, 0.0)
    body.append('<g class="k-anim k-orb-node">'
                + circle(3.0, p['soft'], 0, cx=nx, cy=ny, fill=p['soft'])
                + circle(4.8, p['soft'], 0.7, cx=nx, cy=ny, op='0.7')
                + '</g>')

    # the alidade itself: hairline rule + counterweight + accent index
    hand = math.radians(-58.0)
    al = []
    al.append(line(C + 30 * math.cos(hand), C + 30 * math.sin(hand),
                   C + 196 * math.cos(hand), C + 196 * math.sin(hand),
                   p['ink'], 0.95))
    al.append(line(C + 30 * math.cos(hand), C + 30 * math.sin(hand),
                   C + 196 * math.cos(hand), C + 196 * math.sin(hand),
                   p['gloss'], 2.0, op='0.35'))
    al.append(circle(4.6, p['accent'], 0,
                     cx=C + 196 * math.cos(hand), cy=C + 196 * math.sin(hand),
                     fill=p['accent']))
    al.append(circle(7, p['soft'], 0.85, cx=C, cy=C))
    body.append('<g class="k-anim k-alidade">' + ''.join(al) + '</g>')

    # annotations stay put - they belong to the instrument, not the sky
    body.append(text(C, 62, 'N', p['accent'], size=12, ls=1.6))
    body.append(text(104, 728, '23.44', p['soft'], size=11, ls=1.4))
    return ''.join(defs), ''.join(style), body

# --------------------------------------------------- 2. seed of life
def bloom(p):
    defs, style, o = [], [RM_RULE], []
