# --------------------------------------------------- 6. orthographic globe
def atlas(p):
    """A globe on true orthographic projection: hidden lines are removed, the
    limb is shaded, one great-circle route crosses it."""
    defs, style, o = [], [RM_RULE], []
    R = 262.0
    defs.append(light_grad(p))
    defs.append(metal_grad(p, 'k-metal'))
    TH = math.radians(22.0)     # viewing elevation

    def proj(lat, lon):
        la, lo = math.radians(lat), math.radians(lon)
        x = math.cos(la) * math.sin(lo)
        ys = math.sin(la)
        y = -(ys * math.cos(TH) - math.cos(la) * math.sin(TH) * math.cos(lo))
        z = math.cos(la) * math.cos(TH) * math.cos(lo) + ys * math.sin(TH)
        return (C + R * x, C + R * y, z)

    def curve(kind, fixed, col, w, op=None, dash=None):
        segs, cur, zprev = [], [], None
        rng = [(-84 + i * 3.0) for i in range(57)] if kind == 'mer' else \
              [(-180 + i * 3.0) for i in range(121)]
        for v in rng:
            pt = proj(v, fixed) if kind == 'mer' else proj(fixed, v)
            if pt[2] > 0:
                if not cur:
                    cur = [pt]
                else:
                    cur.append(pt)
            else:
                if len(cur) > 2:
                    segs.append(cur)
                cur = []
        if len(cur) > 2:
            segs.append(cur)
        for s in segs:
            o.append(polyline([(pt[0], pt[1]) for pt in s], col, w, dash=dash, op=op))

    # limb: outer wire + an inner coal ring for volume + key-light crescent
    o.append(circle(R, p['shadow'], 6.0, cx=C + 2.6, cy=C + 3.4, op='0.05'))
    o.append(circle(R - 7, p['coal'], 0.9, op='0.35'))
    o.append(circle(R, p['ink'], 1.15))
    o.append(circle(R, 'url(#k-light)', 2.8, op='0.5'))
    o.append(path(arc(C, C, R, LIGHT_DEG - 74, LIGHT_DEG + 74), p['gloss'], 2.0,
                  op='0.7'))
    o.append(stipple(p, C, C, R - 26, R - 3, 260, seed=41, size=0.55, op='0.14'))

    for lat in (-60, -30, 0, 30, 60):
        curve('par', lat, p['soft'], 0.8 if lat else 1.15,
              op='0.75' if lat else None)
    for lon in range(-75, 90, 15):
        curve('mer', lon, p['ink'], 0.75, op='0.55')

    # one great-circle route, accent, with a node at each end
    a0, a1 = (51.5, -0.1), (-33.9, 18.4)   # a route on the visible hemisphere
    route = []
    steps = 64
    la0, lo0 = math.radians(a0[0]), math.radians(a0[1])
    la1, lo1 = math.radians(a1[0]), math.radians(a1[1])
    dd = math.acos(min(1.0, max(-1.0, math.sin(la0) * math.sin(la1)
                                + math.cos(la0) * math.cos(la1) * math.cos(lo1 - lo0))))
    for i in range(steps + 1):
        tt = i / float(steps)
        A = math.sin((1 - tt) * dd) / math.sin(dd)
        B = math.sin(tt * dd) / math.sin(dd)
        x = A * math.cos(la0) * math.cos(lo0) + B * math.cos(la1) * math.cos(lo1)
        y = A * math.cos(la0) * math.sin(lo0) + B * math.cos(la1) * math.sin(lo1)
        z = A * math.sin(la0) + B * math.sin(la1)
        lat = math.degrees(math.asin(z))
        lon = math.degrees(math.atan2(y, x))
        pt = proj(lat, lon)
        if pt[2] > 0:
            route.append(pt)
    if len(route) > 3:
        o.append(polyline([(pt[0], pt[1]) for pt in route], p['accent'], 1.4, dash=None))
        o.append(polyline([(pt[0], pt[1]) for pt in route], p['gloss'], 2.6, op='0.4'))
    for a in (a0, a1):
        pt = proj(a[0], a[1])
        if pt[2] > 0:
            o.append(circle(4.6, p['accent'], 0.9, cx=pt[0], cy=pt[1]))
            o.append(circle(2.2, p['accent'], 0, cx=pt[0], cy=pt[1],
                            fill=p['accent']))
    o.append(text(C, C + R + 34, 'ORTHOGRAPHIC', p['soft'], size=10, ls=3.4))
    return ''.join(defs), ''.join(style), o

