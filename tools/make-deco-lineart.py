def strip_motion(src):
    """Baked still frame: drop every trace of motion.

    Needed because Chromium does not propagate prefers-reduced-motion into an
    SVG loaded through <img> (verified: the internal media query only fires for
    inlined SVG), so the page must be able to pick a static file instead.
    """
    import re
    out = re.sub(r'\n\s*<style>.*?</style>', '', src, flags=re.S)
    out = re.sub(r'\s*style="animation-duration:[^"]*"', '', out)
    out = re.sub(r'\s*class="[^"]*k-anim[^"]*"', '', out)
    out = re.sub(r';animation-delay:-?[\d.]+s', '', out)
    assert 'animation' not in out, 'motion leaked into the still frame'
    return out


def write(name, body):
    dest = os.path.join(OUT, name)
    if os.path.exists(dest):
        try:
            head = open(dest, 'r', encoding='utf-8').read(400)
        except Exception:
            head = ''
        if MARK not in head:
            print('  SKIP (protected, not generated by this tool): %s' % name)
            return False
    open(dest, 'w', encoding='utf-8', newline='\n').write(body)
    return True


def selftest():
    """Numeric guards - these shapes are generated without being looked at."""
    # seed-of-life: seven circles of equal radius, all mutually overlapping
    r = 104.0
    centres = [(0.0, 0.0)] + [(r * math.cos(math.radians(i * 60)),
                               r * math.sin(math.radians(i * 60))) for i in range(6)]
    assert len(centres) == 7
    # rose window: petals must tile the annulus without overlapping neighbours
    assert abs(math.pi / 12 * 12 - math.pi) < 1e-9
    # moon cycle: illumination must rise monotonically, hitting the exact quarter
    vals = [0.5 * (1 - math.cos(math.pi * i / 8.0)) for i in range(9)]
    assert vals == sorted(vals) and vals[0] == 0.0 and abs(vals[-1] - 1.0) < 1e-9
    assert abs(vals[4] - 0.5) < 1e-9, 'moon 4 must be the exact half'
    assert abs(vals[2] - 0.5 * (1 - math.cos(math.pi / 4))) < 1e-9
    # resonance rose must stay inside its rim
    peak = 0.0
    for i in range(15):
        base, amp, phase = 34.0 + i * 17.8, 3.0 + i * 1.1, i * 0.235
        for d in range(0, 361):
            t = math.radians(d)
            peak = max(peak, base + amp * math.sin(3 * t + phase)
                       + amp * 0.34 * math.sin(7 * t - phase * 1.7))
    assert peak < 320.0, 'rose peak %.1f overflows the rim' % peak
    # armillary: ring stack must nest without colliding with the bezel band
    assert 284.0 - 6.0 > 210.0, 'horizontal ring must clear the inner index ring'
    assert 88.0 + 6.0 < 300.0 - 7.0, 'meridian ring must stay inside the bezel'
    print('  selftest ok: 7 seed circles, quarter moon exact, rose peak %.1f/330' % peak)


