"""R25 - refine the decorative line-art set (light + pre-baked dark variants).

Pure stdlib, no dependencies. Every design is generated twice: once with the
day palette, once with the night palette (never a runtime filter invert).

  deco_armillary[_dark]   - armillary sphere: layered rings, metal gradient,
                            graduation, rivets, specular arc, and slow
                            differential rotation (rings + orbiting markers)
  deco_bloom[_dark]       - seed-of-life core, noise stripped down to the
                            necessary overlapping circles
  deco_phases[_dark]      - moon phases with shading gradient, surface texture,
                            rim light, sequence scale, and a real synodic cycle
  deco_resonance[_dark]   - interference rose (unchanged)
  deco_rosette[_dark]     - rose window skeleton only: frame + mullions + petals

Animation contract: only `transform` and `opacity` animate, nothing else; every
element carries a static base transform/opacity so the reduced-motion frame is
exactly the composed still, and `@media (prefers-reduced-motion: reduce)` kills
the animations. No JS anywhere.

Safety: an existing file is overwritten only if it carries this generator's
marker comment, so no hand-made asset can ever be clobbered.
"""
